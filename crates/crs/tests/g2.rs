//! Gate G2 evidence (Q-14): EPSG identification rate and WGS84 agreement per projection family,
//! against GDAL/PROJ as the oracle (D-08, D-33).
//!
//! Two inputs:
//!
//! - **Corpus**: every layer of `tests/corpus/expected/*.json` (stage01/1.2) with a CRS — its raw
//!   definition (or, for GeoTIFF GeoKeys, the EPSG code GDAL read) and native `extent`, compared
//!   with the golden `epsg` and `wgs84_extent`.
//! - **Fixtures**: every CRS fixture in `tests/data` (stage01/1.4) — identification of each file
//!   against GDAL's, and for each fixture directory two boxes (the CRS's whole area of use and an
//!   inner box) whose native bbox and WGS84 extent GDAL computed (`tests/g2/fixture-oracle.json`,
//!   regenerated by `scripts/run-in-gdal.sh g2_fixture_oracle.py`). Every encoding of the
//!   directory is transformed.
//!
//! WGS84 tolerance is D-33's: each edge within 0.01°, longitudes modulo 360, longitude span within
//! 0.02°. Identification agrees when both give the same EPSG code or both give none.
//!
//! Run with `cargo test -p whereabouts-crs --test g2 -- --nocapture` to see the report. The test
//! fails if a rate drops below the floors at the bottom of this file (the measured values when
//! G2 was evaluated).

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::Value;
use whereabouts_core::{AuthorityCode, Bounds, CrsDefinition, CrsDefinitionKind, Wgs84Extent};
use whereabouts_crs::{Crs, CrsKind, ProjectionMethod as M, resolve, transform_bounds};

const WGS84_TOL: f64 = 0.01;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")
}

/// Projection family for the report.
fn family(crs: Option<&Crs>) -> String {
    let Some(h) = crs.and_then(Crs::horizontal) else {
        return match crs.map(|c| c.kind) {
            Some(k) => format!("({k:?})").to_lowercase(),
            None => "(unparsed)".to_owned(),
        };
    };
    if h.kind == CrsKind::Geographic {
        return "geographic".to_owned();
    }
    let Some(p) = &h.projection else {
        return "(no projection)".to_owned();
    };
    match p.method {
        M::TransverseMercator | M::TransverseMercatorSouthOrientated => {
            "transverse mercator".into()
        }
        M::LambertConicConformal1Sp
        | M::LambertConicConformal2Sp
        | M::LambertConicConformal2SpBelgium => "lambert conformal conic".into(),
        M::AlbersEqualArea => "albers".into(),
        M::MercatorVariantA | M::MercatorVariantB => "mercator".into(),
        M::PopularVisualisationPseudoMercator => "web mercator".into(),
        M::PolarStereographicVariantA
        | M::PolarStereographicVariantB
        | M::PolarStereographicVariantC => "polar stereographic".into(),
        other => format!("{other:?}").to_lowercase(),
    }
}

type Bbox = [f64; 4];

fn lon_span(b: &Bbox) -> f64 {
    let (w, e) = (b[0], b[2]);
    if e >= w { e - w } else { e - w + 360.0 }
}

fn wgs84_close(e: &Bbox, a: &Bbox) -> bool {
    let lon = |x: f64, y: f64| {
        let d = (x - y).rem_euclid(360.0);
        d.min(360.0 - d) <= WGS84_TOL
    };
    let lat = |x: f64, y: f64| (x - y).abs() <= WGS84_TOL;
    (lon_span(e) - lon_span(a)).abs() <= 2.0 * WGS84_TOL
        && lon(e[0], a[0])
        && lat(e[1], a[1])
        && lon(e[2], a[2])
        && lat(e[3], a[3])
}

/// `[west, south, east, north]` of an extent (west > east when split at the antimeridian).
fn wsen(x: &Wgs84Extent) -> Bbox {
    let parts = x.parts();
    let s = parts
        .iter()
        .map(|p| p.min_y())
        .fold(f64::INFINITY, f64::min);
    let n = parts
        .iter()
        .map(|p| p.max_y())
        .fold(f64::NEG_INFINITY, f64::max);
    if parts.len() == 2 {
        let (east_part, west_part) = if parts[0].max_x() == 180.0 {
            (&parts[1], &parts[0])
        } else {
            (&parts[0], &parts[1])
        };
        [west_part.min_x(), s, east_part.max_x(), n]
    } else {
        [parts[0].min_x(), s, parts[0].max_x(), n]
    }
}

fn bbox(v: &Value) -> Option<Bbox> {
    let a = v.as_array()?;
    Some([
        a.first()?.as_f64()?,
        a.get(1)?.as_f64()?,
        a.get(2)?.as_f64()?,
        a.get(3)?.as_f64()?,
    ])
}

#[derive(Default)]
struct Tally {
    id_total: usize,
    id_agree: usize,
    /// Cases where the oracle identified an EPSG code.
    id_expected: usize,
    /// ... and we found the same one.
    id_found: usize,
    /// We gave a code the oracle did not (or a different one).
    id_wrong: usize,
    tf_total: usize,
    tf_agree: usize,
    tf_partial: usize,
}

#[derive(Default)]
struct Report {
    families: BTreeMap<String, Tally>,
    failures: Vec<String>,
}

impl Report {
    fn identification(&mut self, case: &str, family: &str, ours: Option<u32>, gold: Option<u32>) {
        let t = self.families.entry(family.to_owned()).or_default();
        t.id_total += 1;
        if gold.is_some() {
            t.id_expected += 1;
        }
        if ours == gold {
            t.id_agree += 1;
            if gold.is_some() {
                t.id_found += 1;
            }
        } else {
            if ours.is_some() {
                t.id_wrong += 1;
            }
            self.failures.push(format!(
                "identify | {case} | {family} | ours {ours:?} vs GDAL {gold:?}"
            ));
        }
    }

    fn transform(
        &mut self,
        case: &str,
        family: &str,
        ours: Result<(Bbox, bool), String>,
        gold: Bbox,
    ) {
        let t = self.families.entry(family.to_owned()).or_default();
        t.tf_total += 1;
        match ours {
            Ok((b, partial)) => {
                if partial {
                    t.tf_partial += 1;
                }
                if wgs84_close(&b, &gold) {
                    t.tf_agree += 1;
                } else {
                    self.failures.push(format!(
                        "wgs84 | {case} | {family} | ours {} vs GDAL {}{}",
                        fmt_box(&b),
                        fmt_box(&gold),
                        if partial { " (partial)" } else { "" }
                    ));
                }
            }
            Err(e) => self.failures.push(format!(
                "wgs84 | {case} | {family} | error: {e} vs GDAL {}",
                fmt_box(&gold)
            )),
        }
    }

    fn totals(&self) -> Tally {
        let mut all = Tally::default();
        for t in self.families.values() {
            all.id_total += t.id_total;
            all.id_agree += t.id_agree;
            all.id_expected += t.id_expected;
            all.id_found += t.id_found;
            all.id_wrong += t.id_wrong;
            all.tf_total += t.tf_total;
            all.tf_agree += t.tf_agree;
            all.tf_partial += t.tf_partial;
        }
        all
    }

    fn markdown(&self, title: &str) -> String {
        let mut s = String::new();
        writeln!(s, "\n### {title}\n").unwrap();
        writeln!(
            s,
            "| family | identification agrees | EPSG found (of GDAL-identified) | wrong code | WGS84 agrees | partial |"
        )
        .unwrap();
        writeln!(s, "|---|---|---|---|---|---|").unwrap();
        let row = |name: &str, t: &Tally| {
            format!(
                "| {name} | {} | {} | {} | {} | {} |",
                ratio(t.id_agree, t.id_total),
                ratio(t.id_found, t.id_expected),
                t.id_wrong,
                ratio(t.tf_agree, t.tf_total),
                t.tf_partial
            )
        };
        for (name, t) in &self.families {
            writeln!(s, "{}", row(name, t)).unwrap();
        }
        writeln!(s, "{}", row("**all**", &self.totals())).unwrap();
        if !self.failures.is_empty() {
            writeln!(s, "\nDisagreements ({}):\n", self.failures.len()).unwrap();
            for f in &self.failures {
                writeln!(s, "- {f}").unwrap();
            }
        }
        s
    }
}

fn ratio(a: usize, b: usize) -> String {
    if b == 0 {
        "–".to_owned()
    } else {
        format!("{a}/{b} ({:.1}%)", 100.0 * a as f64 / b as f64)
    }
}

fn fmt_box(b: &Bbox) -> String {
    format!("[{:.4}, {:.4}, {:.4}, {:.4}]", b[0], b[1], b[2], b[3])
}

fn run_transform(crs: Option<&Crs>, native: Bbox) -> Result<(Bbox, bool), String> {
    let crs = crs.ok_or("no CRS model")?;
    let mut native = native;
    if native[0] > native[2] {
        // GDAL reports a geographic area crossing the antimeridian as west > east; a file stores
        // such data as e.g. 160.6..188.8.
        native[2] += 360.0;
    }
    let bounds =
        Bounds::new(native[0], native[1], native[2], native[3]).map_err(|e| e.to_string())?;
    let t = transform_bounds(&bounds, crs).map_err(|e| e.to_string())?;
    Ok((wsen(&t.extent), t.partial.is_some()))
}

fn def_kind(raw_kind: &str) -> Option<CrsDefinitionKind> {
    Some(match raw_kind {
        "wkt1_esri" => CrsDefinitionKind::Wkt1Esri,
        "wkt1" => CrsDefinitionKind::Wkt1,
        "wkt2" => CrsDefinitionKind::Wkt2,
        "projjson" => CrsDefinitionKind::ProjJson,
        _ => return None,
    })
}

fn corpus_report() -> Report {
    let mut report = Report::default();
    let dir = repo_root().join("tests").join("corpus").join("expected");
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .expect("tests/corpus/expected")
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    for f in files {
        let doc: Value = serde_json::from_str(&std::fs::read_to_string(&f).unwrap()).unwrap();
        let case = doc["case"].as_str().unwrap_or("?").to_owned();
        for layer in doc["layers"].as_array().into_iter().flatten() {
            let crs = &layer["crs"];
            if crs["status"].as_str() == Some("missing") || crs.is_null() {
                continue;
            }
            let id = format!("{case}/{}", layer["name"].as_str().unwrap_or("?"));
            let gold_epsg = crs["epsg"].as_u64().map(|v| v as u32);
            // Input: the raw text; GeoKeys (no text here until 3.2) fall back to the code GDAL
            // read from the file, which exercises the EPSG table path.
            let raw = crs["raw"].as_str().unwrap_or("");
            let def = match def_kind(crs["raw_kind"].as_str().unwrap_or("")) {
                Some(kind) if !raw.is_empty() => {
                    let mut d = CrsDefinition::new(kind, raw);
                    if let Some(a) = crs["declared_authority"].as_object()
                        && let (Some(n), Some(c)) = (a["name"].as_str(), a["code"].as_str())
                    {
                        d.authority = Some(AuthorityCode {
                            authority: n.to_owned(),
                            code: c.to_owned(),
                        });
                    }
                    d
                }
                _ => match gold_epsg {
                    Some(code) => CrsDefinition::epsg(code),
                    None => continue,
                },
            };
            let r = resolve(&def);
            let fam = family(r.crs.as_ref());
            report.identification(&id, &fam, r.resolved.epsg(), gold_epsg);
            if let (Some(native), Some(gold)) =
                (bbox(&layer["extent"]), bbox(&layer["wgs84_extent"]))
            {
                report.transform(&id, &fam, run_transform(r.crs.as_ref(), native), gold);
            }
        }
    }
    report
}

fn fixture_report() -> Report {
    let mut report = Report::default();
    let base = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let oracle: Value = serde_json::from_str(
        &std::fs::read_to_string(base.join("g2").join("fixture-oracle.json")).unwrap(),
    )
    .unwrap();
    let data = base.join("data");
    let parse = |fixture: &str| {
        let bytes = std::fs::read(data.join(fixture)).unwrap();
        whereabouts_crs::parse_bytes(&bytes).ok()
    };
    for rec in oracle["identify"].as_array().unwrap() {
        let fixture = rec["fixture"].as_str().unwrap();
        if rec["parsed"].as_bool() != Some(true) {
            continue; // GDAL can't read it either (ESRI VERTCS-only files)
        }
        let crs = parse(fixture);
        let ours = crs
            .as_ref()
            .and_then(whereabouts_crs::identify)
            .map(|i| i.epsg);
        let gold = rec["epsg"].as_u64().map(|v| v as u32);
        report.identification(fixture, &family(crs.as_ref()), ours, gold);
    }
    for rec in oracle["transform"].as_array().unwrap() {
        let dir = rec["fixture"].as_str().unwrap();
        let mut files: Vec<String> = std::fs::read_dir(data.join(dir))
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        files.sort();
        for b in rec["boxes"].as_array().unwrap() {
            let (Some(native), Some(gold)) = (bbox(&b["native"]), bbox(&b["wgs84"])) else {
                continue;
            };
            for file in &files {
                let fixture = format!("{dir}/{file}");
                let crs = parse(&fixture);
                let case = format!("{fixture} [{}]", b["box"].as_str().unwrap_or("?"));
                report.transform(
                    &case,
                    &family(crs.as_ref()),
                    run_transform(crs.as_ref(), native),
                    gold,
                );
            }
        }
    }
    report
}

#[test]
fn g2_report() {
    let corpus = corpus_report();
    let fixtures = fixture_report();
    let mut md = String::from(
        "## G2 — CRS identification and WGS84 agreement vs GDAL 3.13.3 / PROJ 9.8.1\n",
    );
    md.push_str(&corpus.markdown("Corpus (tests/corpus/expected, stage01/1.2)"));
    md.push_str(&fixtures.markdown("CRS fixtures (crates/crs/tests/data, stage01/1.4)"));
    println!("{md}");
    if let Ok(path) = std::env::var("G2_REPORT") {
        std::fs::write(path, &md).unwrap();
    }

    // Floors: the rates measured when G2 was evaluated (see the session 2.4 note). A drop is a
    // regression.
    let c = corpus.totals();
    let f = fixtures.totals();
    assert!(
        rate(c.id_agree, c.id_total) >= FLOOR_CORPUS_ID,
        "corpus identification dropped"
    );
    assert!(
        rate(c.tf_agree, c.tf_total) >= FLOOR_CORPUS_WGS84,
        "corpus WGS84 dropped"
    );
    assert!(
        rate(f.id_agree, f.id_total) >= FLOOR_FIXTURE_ID,
        "fixture identification dropped"
    );
    assert!(
        rate(f.tf_agree, f.tf_total) >= FLOOR_FIXTURE_WGS84,
        "fixture WGS84 dropped"
    );
    assert_eq!(c.id_wrong, 0, "corpus: a wrong EPSG code was given");
}

/// EPSG-wide sweep: every non-deprecated EPSG geographic 2D / projected CRS. WGS84 agreement of
/// an inner box (20% of the area of use) transformed from the embedded table's definition, and
/// identification of the CRS's ESRI WKT export (what ArcGIS/QGIS write to `.prj`), compared with
/// the true code and with GDAL's identification of the same text.
#[test]
#[ignore = "needs tests/g2/epsg-sweep.jsonl: scripts/run-in-gdal.sh g2_fixture_oracle.py --epsg-sweep"]
fn g2_epsg_sweep() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("g2")
        .join("epsg-sweep.jsonl");
    let text = std::fs::read_to_string(&path).expect("epsg-sweep.jsonl (see #[ignore] reason)");
    let mut transform = Report::default();
    let mut esri_vs_gdal = Report::default();
    // ESRI export identified as its own code, per family: (found, total).
    let mut esri_vs_truth: BTreeMap<String, (usize, usize, usize)> = BTreeMap::new();
    let mut other_codes: Vec<String> = Vec::new();
    for line in text.lines() {
        // Older sweeps wrote non-finite GDAL output as bare NaN/Infinity tokens.
        let line = line
            .replace("-Infinity", "null")
            .replace("Infinity", "null")
            .replace("NaN", "null");
        let rec: Value = serde_json::from_str(&line).unwrap();
        let code = rec["epsg"].as_u64().unwrap() as u32;
        let model = whereabouts_crs::epsg_crs(code);
        let fam = family(model.as_ref());
        for b in rec["boxes"].as_array().into_iter().flatten() {
            if let (Some(native), Some(gold)) = (bbox(&b["native"]), bbox(&b["wgs84"])) {
                let case = format!("EPSG:{code}");
                transform.transform(&case, &fam, run_transform(model.as_ref(), native), gold);
            }
        }
        if let Some(esri) = rec["esri"].as_str() {
            let parsed = whereabouts_crs::parse(esri).ok();
            let ours = parsed
                .as_ref()
                .and_then(whereabouts_crs::identify)
                .map(|i| i.epsg);
            let gold = rec["esri_identify"]["epsg"].as_u64().map(|v| v as u32);
            esri_vs_gdal.identification(&format!("EPSG:{code} as ESRI WKT"), &fam, ours, gold);
            let e = esri_vs_truth.entry(fam.clone()).or_default();
            e.1 += 1;
            match ours {
                Some(c) if c == code => e.0 += 1,
                Some(c) => {
                    e.2 += 1;
                    other_codes.push(format!("EPSG:{code} as ESRI WKT identified as EPSG:{c}"));
                }
                None => {}
            }
        }
    }
    let mut md = String::from("## G2 — EPSG-wide sweep vs GDAL 3.13.3 / PROJ 9.8.1\n");
    // Keep the failure lists short in the printed report: summarise by family.
    let summarize = |r: &Report, title: &str| {
        let mut short = Report {
            families: BTreeMap::new(),
            failures: Vec::new(),
        };
        for (k, v) in &r.families {
            short.families.insert(
                k.clone(),
                Tally {
                    id_total: v.id_total,
                    id_agree: v.id_agree,
                    id_expected: v.id_expected,
                    id_found: v.id_found,
                    id_wrong: v.id_wrong,
                    tf_total: v.tf_total,
                    tf_agree: v.tf_agree,
                    tf_partial: v.tf_partial,
                },
            );
        }
        let mut s = short.markdown(title);
        let limit = if std::env::var_os("G2_SWEEP_REPORT").is_some() {
            usize::MAX
        } else {
            60
        };
        writeln!(s, "\nDisagreements: {} (first {limit})\n", r.failures.len()).unwrap();
        for f in r.failures.iter().take(limit) {
            writeln!(s, "- {f}").unwrap();
        }
        s
    };
    md.push_str(&summarize(
        &transform,
        "WGS84 agreement, inner box, EPSG table definition",
    ));
    md.push_str(&summarize(
        &esri_vs_gdal,
        "ESRI WKT export: our identification vs GDAL's",
    ));
    md.push_str(
        "\n### ESRI WKT export identified as its own EPSG code\n\n\
         | family | own code found | another code given |\n|---|---|---|\n",
    );
    let (mut found, mut total, mut other) = (0, 0, 0);
    for (fam, (f, t, o)) in &esri_vs_truth {
        writeln!(md, "| {fam} | {} | {o} |", ratio(*f, *t)).unwrap();
        found += f;
        total += t;
        other += o;
    }
    writeln!(md, "| **all** | {} | {other} |", ratio(found, total)).unwrap();
    for o in &other_codes {
        writeln!(md, "- {o}").unwrap();
    }
    println!("{md}");
    if let Ok(path) = std::env::var("G2_SWEEP_REPORT") {
        std::fs::write(path, &md).unwrap();
    }
    let t = transform.totals();
    assert!(t.tf_total > 5000);
    assert!(
        rate(t.tf_agree, t.tf_total) >= FLOOR_SWEEP_WGS84,
        "sweep WGS84 dropped"
    );
    assert!(
        rate(found, total) >= FLOOR_SWEEP_ESRI_ID,
        "sweep ESRI identification dropped"
    );
}

fn rate(a: usize, b: usize) -> f64 {
    a as f64 / b.max(1) as f64
}

const FLOOR_SWEEP_WGS84: f64 = 0.985;
const FLOOR_SWEEP_ESRI_ID: f64 = 0.998;

const FLOOR_CORPUS_ID: f64 = 1.0;
const FLOOR_CORPUS_WGS84: f64 = 1.0;
const FLOOR_FIXTURE_ID: f64 = 0.99;
const FLOOR_FIXTURE_WGS84: f64 = 0.99;
