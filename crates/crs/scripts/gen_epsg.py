"""Generates crates/crs/data/epsg.txt, the embedded EPSG table of whereabouts-crs.

Runs inside the pinned GDAL image (see run-in-gdal.sh) and reads PROJ's proj.db, which carries
the EPSG Geodetic Parameter Dataset plus Esri's names for EPSG objects. Only what EPSG
identification and bbox transformation need is kept, with every value converted to degrees /
metres / unity so the Rust side never deals with EPSG units of measure:

    # comment lines (provenance)
    D|code|name|a_m|rf|pm_deg|aliases                                  geodetic datum
    G|code|name|datum|angle_to_deg|axes|flags|towgs84|aliases          geographic 2D/3D CRS
    P|code|name|base|method|params|metres_per_unit|axes|flags|aliases  projected CRS

- `rf` is the inverse flattening, 0 for a sphere.
- `angle_to_deg` converts the geographic CRS's angular unit to degrees (1 for degrees, 0.9 for
  grads).
- `axes`: two letters for the first two axes, e/w/n/s, or `o` for anything else ("North along
  90°E").
- `flags`: `d` deprecated, `3` geographic 3D.
- `towgs84`: dx,dy,dz (m),rx,ry,rz (arc-seconds, position-vector convention),ds (ppm) of the most
  accurate non-deprecated Helmert transformation to EPSG:4326, or empty.
- `params`: comma-separated `epsg_parameter_code:value`, angles in degrees, lengths in metres,
  scales as plain numbers.
- `aliases`: `;`-separated alternative names (EPSG aliases and Esri names).

Output is deterministic (sorted by code, floats written with repr).
"""

import sqlite3
import sys
from decimal import Decimal
from pathlib import Path

DB = "/usr/share/proj/proj.db"
OUT = Path("crates/crs/data/epsg.txt")

con = sqlite3.connect(DB)
q = lambda sql, *args: con.execute(sql, args).fetchall()

meta = dict(q("SELECT key, value FROM metadata"))
UOM = {
    code: (typ, factor)
    for code, typ, factor in q(
        "SELECT code, type, conv_factor FROM unit_of_measure WHERE auth_name = 'EPSG'"
    )
}


def fmt(v: float) -> str:
    r = repr(float(v))
    if r.endswith(".0"):
        r = r[:-2]
    return "0" if r == "-0" else r


def dms_to_deg(value: float) -> float:
    """EPSG 9110 'sexagesimal DMS' (DDD.MMSSsss) to decimal degrees."""
    s = format(Decimal(repr(value)), "f")
    neg = s.startswith("-")
    s = s.lstrip("-")
    ip, _, fp = s.partition(".")
    fp = (fp + "0000")
    minutes = int(fp[0:2])
    seconds = Decimal(fp[2:4] + "." + (fp[4:] or "0"))
    deg = Decimal(ip) + Decimal(minutes) / 60 + seconds / 3600
    return float(-deg if neg else deg)


def angle_deg(value, uom) -> float:
    if uom == 9110:
        return dms_to_deg(value)
    if uom in (9102, 9122):
        return float(value)
    if uom == 9105:
        return float(value) * 0.9
    typ, factor = UOM[uom]
    assert typ == "angle", (uom, typ)
    if factor is None:
        # Sexagesimal *representations* of the degree (9107, 9108, 9115...) only label how a
        # coordinate is displayed; the axis unit is the degree. Parameter values never use them
        # (only 9110, handled above), so this branch only sees coordinate-system axes.
        return float(value)
    return float(value) * factor * 180.0 / 3.141592653589793


def length_m(value, uom) -> float:
    typ, factor = UOM[uom]
    assert typ == "length" and factor, (uom, typ)
    return float(value) * factor


def convert(value, uom) -> float:
    typ, _ = UOM[uom]
    if typ == "angle":
        return angle_deg(value, uom)
    if typ == "length":
        return length_m(value, uom)
    if typ == "scale":
        return float(value) * UOM[uom][1]
    raise ValueError(f"unexpected unit {uom} ({typ})")


def clean(name: str) -> str:
    if any(ch in name for ch in "|;\n\r"):
        raise ValueError(f"name contains a separator: {name!r}")
    return name


def aliases(table: str, code) -> str:
    rows = q(
        "SELECT DISTINCT alt_name FROM alias_name WHERE table_name = ? AND auth_name = 'EPSG' "
        "AND code = ? ORDER BY alt_name",
        table,
        str(code),
    )
    # Purely numeric aliases ("246") are legacy codes, not names.
    return ";".join(clean(r[0]) for r in rows if any(ch.isalpha() for ch in r[0]))


AXIS = {"east": "e", "west": "w", "north": "n", "south": "s"}


def axes(cs_auth, cs_code):
    rows = q(
        "SELECT orientation, uom_code FROM axis WHERE coordinate_system_auth_name = ? AND "
        "coordinate_system_code = ? ORDER BY coordinate_system_order",
        cs_auth,
        cs_code,
    )
    letters = "".join(AXIS.get(o.lower(), "o") for o, _ in rows[:2])
    return letters, (rows[0][1] if rows else None)


lines = [
    "# whereabouts-crs embedded EPSG table. GENERATED by crates/crs/scripts/gen_epsg.py; do not edit.",
    f"# Source: EPSG Geodetic Parameter Dataset {meta['EPSG.VERSION']} ({meta['EPSG.DATE']}),"
    f" as packaged in PROJ {meta['PROJ.VERSION']} proj.db (PROJ-data {meta['PROJ_DATA.VERSION']}).",
    "# The EPSG Dataset is (c) IOGP, used under the EPSG terms of use (https://epsg.org/terms-of-use.html).",
    f"# Esri names: Esri projection engine definitions ({meta['ESRI.VERSION']}), Apache License 2.0,"
    " via PROJ.",
    "# Values are converted to degrees / metres / unity; see gen_epsg.py for the record layout.",
]

# ---- geographic CRSs -------------------------------------------------------------------------
geog = q(
    "SELECT code, name, type, coordinate_system_auth_name, coordinate_system_code, datum_auth_name,"
    " datum_code, deprecated FROM geodetic_crs WHERE auth_name = 'EPSG' AND type IN"
    " ('geographic 2D', 'geographic 3D') ORDER BY CAST(code AS INTEGER)"
)
datums = set()
g_lines = []
for code, name, typ, cs_auth, cs_code, d_auth, d_code, deprecated in geog:
    if d_auth != "EPSG":
        continue
    datums.add(int(d_code))
    letters, uom = axes(cs_auth, cs_code)
    to_deg = angle_deg(1.0, uom) if uom else 1.0
    flags = ("d" if deprecated else "") + ("3" if typ == "geographic 3D" else "")
    helmerts = q(
        "SELECT code, method_code, accuracy, tx, ty, tz, translation_uom_code, rx, ry, rz,"
        " rotation_uom_code, scale_difference, scale_difference_uom_code FROM"
        " helmert_transformation_table WHERE auth_name = 'EPSG' AND source_crs_auth_name = 'EPSG'"
        " AND source_crs_code = ? AND target_crs_auth_name = 'EPSG' AND target_crs_code = 4326"
        " AND deprecated = 0 AND method_code IN (9603, 9606, 9607)",
        code,
    )
    helmerts.sort(key=lambda h: (h[2] if h[2] is not None else 1e9, int(h[0])))
    towgs84 = ""
    if helmerts:
        _, method, _, tx, ty, tz, tu, rx, ry, rz, ru, ds, du = helmerts[0]
        t = [length_m(v, tu) for v in (tx, ty, tz)]
        if method == 9603:
            r, s = [0.0, 0.0, 0.0], 0.0
        else:
            r = [angle_deg(v, ru) * 3600.0 for v in (rx, ry, rz)]
            if method == 9607:  # coordinate frame -> position vector
                r = [-v for v in r]
            s = float(ds) * UOM[du][1] * 1e6
        towgs84 = ",".join(fmt(v) for v in t + r + [s])
    g_lines.append(
        "|".join(
            [
                "G",
                str(code),
                clean(name),
                str(d_code),
                fmt(to_deg),
                letters,
                flags,
                towgs84,
                aliases("geodetic_crs", code),
            ]
        )
    )

# ---- projected CRSs --------------------------------------------------------------------------
proj = q(
    "SELECT p.code, p.name, p.coordinate_system_auth_name, p.coordinate_system_code,"
    " p.geodetic_crs_auth_name, p.geodetic_crs_code, p.conversion_auth_name, p.conversion_code,"
    " p.deprecated FROM projected_crs p WHERE p.auth_name = 'EPSG' ORDER BY CAST(p.code AS INTEGER)"
)
p_lines = []
for code, name, cs_auth, cs_code, g_auth, g_code, c_auth, c_code, deprecated in proj:
    if g_auth != "EPSG":
        continue
    conv = q(
        "SELECT * FROM conversion_table WHERE auth_name = ? AND code = ?", c_auth, c_code
    )
    if not conv:
        continue
    row = conv[0]
    method = row[5]
    params = []
    for i in range(7):
        base = 6 + i * 5
        p_auth, p_code, value, u_auth, u_code = row[base : base + 5]
        if p_code is None:
            continue
        if value is None or u_code is None:
            params = None
            break
        params.append(f"{p_code}:{fmt(convert(value, u_code))}")
    if params is None:
        continue
    letters, uom = axes(cs_auth, cs_code)
    unit = length_m(1.0, uom) if uom else 1.0
    flags = "d" if deprecated else ""
    p_lines.append(
        "|".join(
            [
                "P",
                str(code),
                clean(name),
                str(g_code),
                str(method),
                ",".join(params),
                fmt(unit),
                letters,
                flags,
                aliases("projected_crs", code),
            ]
        )
    )

# ---- datums ----------------------------------------------------------------------------------
d_lines = []
for d_code in sorted(datums):
    rows = q(
        "SELECT d.name, e.semi_major_axis, e.uom_code, e.inv_flattening, e.semi_minor_axis,"
        " pm.longitude, pm.uom_code FROM geodetic_datum d JOIN ellipsoid e ON"
        " e.auth_name = d.ellipsoid_auth_name AND e.code = d.ellipsoid_code JOIN prime_meridian pm"
        " ON pm.auth_name = d.prime_meridian_auth_name AND pm.code = d.prime_meridian_code"
        " WHERE d.auth_name = 'EPSG' AND d.code = ?",
        d_code,
    )
    if not rows:
        print(f"warning: datum {d_code} not found", file=sys.stderr)
        continue
    name, a, a_uom, rf, b, pm, pm_uom = rows[0]
    a_m = length_m(a, a_uom)
    if rf is None:
        b_m = length_m(b, a_uom)
        rf = 0.0 if b_m == a_m else a_m / (a_m - b_m)
    d_lines.append(
        "|".join(
            [
                "D",
                str(d_code),
                clean(name),
                fmt(a_m),
                fmt(rf),
                fmt(angle_deg(pm, pm_uom)),
                aliases("geodetic_datum", d_code),
            ]
        )
    )

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines + d_lines + g_lines + p_lines) + "\n", encoding="utf-8")
print(
    f"wrote {OUT}: {len(d_lines)} datums, {len(g_lines)} geographic, {len(p_lines)} projected",
    file=sys.stderr,
)
